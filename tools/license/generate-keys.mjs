// Generates your license signing key pair (ECDSA P-256).
// - keys/private-key.pem  KEEP SECRET. Never commit or ship it.
// - writes the public key into src/webparts/brillientaCrm/models/licensePublicKey.ts
// Usage: node tools/license/generate-keys.mjs [--force]
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const keyDir = join(here, 'keys');
const privPath = join(keyDir, 'private-key.pem');
if (existsSync(privPath) && !process.argv.includes('--force')) {
  console.error('Key already exists. Re-run with --force to replace it (all issued licenses become invalid).');
  process.exit(1);
}
const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
mkdirSync(keyDir, { recursive: true });
writeFileSync(privPath, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });
const jwk = publicKey.export({ format: 'jwk' });
const out = join(here, '../../src/webparts/brillientaCrm/models/licensePublicKey.ts');
writeFileSync(out, `// Generated by tools/license/generate-keys.mjs. Public key only - safe to ship.\nexport const LICENSE_PUBLIC_KEY: JsonWebKey = ${JSON.stringify({ kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y })};\n`);
console.log('Private key:', privPath);
console.log('Public key written to', out, '- rebuild the solution.');
